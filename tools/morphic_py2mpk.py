#!/usr/bin/env python3
"""
MorphicPy AOT Transpiler (Python -> Native Ring-3 C++ -> .mpk)
Compiles safe, declarative Python MorphicUI scripts into zero-overhead native x86_64 .mpk apps.

Usage:
    python tools/morphic_py2mpk.py userspace/apps/<app>/app.py
"""

import ast
import sys
from pathlib import Path


def transpile_py_to_cpp(py_path: Path) -> str:
    tree = ast.parse(py_path.read_text(encoding="utf-8"), filename=str(py_path))
    title = py_path.parent.name.capitalize()
    subtitle = "Compiled with MorphicPy AOT SDK"
    width, height = 540, 320
    render_stmts = []

    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
            if isinstance(node.value, ast.Constant):
                if name == "TITLE": title = str(node.value.value)
                elif name == "SUBTITLE": subtitle = str(node.value.value)
                elif name == "WIDTH": width = int(node.value.value)
                elif name == "HEIGHT": height = int(node.value.value)
        elif isinstance(node, ast.FunctionDef) and node.name == "on_render":
            for stmt in node.body:
                if isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Call):
                    call = stmt.value
                    if isinstance(call.func, ast.Attribute) and isinstance(call.func.value, ast.Name):
                        obj, method = call.func.value.id, call.func.attr
                        args = [a.value for a in call.args if isinstance(a, ast.Constant)]
                        if obj == "ui" and method == "card" and len(args) == 4:
                            render_stmts.append(f"        MorphicUI::DrawCard(g, {{{int(args[0])}, {int(args[1])}, {int(args[2])}, {int(args[3])}}});")
                        elif obj == "ui" and method == "text" and len(args) == 3:
                            esc = str(args[2]).replace('"', '\\"')
                            render_stmts.append(f'        g.DrawText({int(args[0])}, {int(args[1])}, "{esc}", MorphicUI::Theme::TEXT_PRIMARY, 1);')
                        elif obj == "ui" and method == "badge" and len(args) == 3:
                            esc = str(args[2]).replace('"', '\\"')
                            render_stmts.append(f'        MorphicUI::DrawBadge(g, {int(args[0])}, {int(args[1])}, "{esc}");')

    body_code = "\n".join(render_stmts) if render_stmts else '        g.DrawText(24, 80, "Hello from MorphicPy!", MorphicUI::Theme::ACCENT_CYAN, 1);'
    return f"""// Auto-generated by tools/morphic_py2mpk.py from {py_path.name}
#include "../../sdk/morphic_api.h"
#include "../../sdk/morphic_ui.h"
#include "../../sdk/morphic_hw.h"

class MorphicPyApp : public MorphicAPI::Window {{
public:
    MorphicPyApp() : MorphicAPI::Window({width}, {height}) {{}}
    void OnUpdate() override {{}}
    void OnRender(MorphicAPI::Graphics& g) override {{
        MorphicUI::DrawWindowBackdrop(g);
        MorphicUI::DrawHeaderBar(g, "{title}", "{subtitle}");
{body_code}
    }}
}};

extern "C" int main(void* args) {{
    (void)args;
    MorphicPyApp app;
    app.Run();
    return 0;
}}
"""


def main():
    if len(sys.argv) < 2:
        print("Usage: python tools/morphic_py2mpk.py <path/to/app.py>")
        sys.exit(1)
    py_path = Path(sys.argv[1]).resolve()
    out_cpp = py_path.parent / "main.cpp"
    out_cpp.write_text(transpile_py_to_cpp(py_path), encoding="utf-8")
    print(f"[MorphicPy] Transpiled {py_path.name} -> {out_cpp}")


if __name__ == "__main__":
    main()
